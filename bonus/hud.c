void label(t_bonus *g, int x, int y, const char *s, int scale, int color)
{
	const char *chars = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ:/-";
	const char *p;
	for (; *s; ++s, x += 6 * scale)
	{
		p = strchr(chars, *s);
		if (!p)
			continue ;
		for (int col = 0; col < 5; ++col)
			for (int row = 0; row < 7; ++row)
				if (g_font[p - chars][col] & (1 << row))
					rect(g, x + col * scale, y + row * scale, scale, scale, color);
	}
}

static void minimap(t_bonus *g)
{
	int cx = (int)g->x, cy = (int)g->y, color;
	t_door *d;
	rect(g, 8, 8, 108, 108, 0x202020);
	for (int y = -6; y <= 6; ++y)
		for (int x = -6; x <= 6; ++x)
		{
			color = 0xdddddd;
			if (cell(g, cx + x, cy + y) == '1')
				color = 0x666666;
			if (cell(g, cx + x, cy + y) == ' ')
				color = 0x202020;
			d = door_at(g, cx + x, cy + y);
			if (d)
				color = d->open >= 1 ? 0x79a978 : 0xc18b45;
			rect(g, 10 + (x + 6) * 8, 10 + (y + 6) * 8, 7, 7, color);
		}
	rect(g, 60, 60, 4, 4, 0xd64236);
	for (int i = 0; i < 10; ++i)
		pixel(g, 62 + cos(g->angle) * i, 62 + sin(g->angle) * i, 0xd64236);
}

void render_hud(t_bonus *g)
{
	char text[32];
	if (g->minimap)
		minimap(g);
	if (g->show_fps)
	{
		snprintf(text, sizeof(text), "FPS %03d", (int)g->fps);
		rect(g, BW - 67, 8, 59, 15, 0x202020);
		label(g, BW - 63, 12, text, 1, 0xffffff);
	}
	if (!g->focused)
	{
		rect(g, BW / 2 - 28, BH / 2 - 10, 56, 20, 0x202020);
		label(g, BW / 2 - 23, BH / 2 - 4, "PAUSE", 1, 0xffffff);
	}
}
